/**
 * 查调候用神：按日主 + 月支。
 * 未知组合（理论上不会发生）回退为空结果而非抛错。
 */
export function computeTiaoHou(dayGan: string, monthZhi: string): TiaoHouResult {
  const cell = TIAO_HOU[dayGan]?.[monthZhi] ?? "";
  const chars = cell.split("").filter((c) => "甲乙丙丁戊己庚辛壬癸".includes(c));
  const primary = chars[0] ?? "";
  const secondary = chars.slice(1);
  const note = MONTH_CLIMATE[monthZhi] ?? "";
  return { primary, secondary, monthZhi, note };
}

/** 该月支藏干（透干取用与本格判定共用） */
export function getMonthHiddenStems(monthZhi: string): string[] {
  return MONTH_HIDDEN_STEMS[monthZhi] ?? [];
}
